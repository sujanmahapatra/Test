// Plans -> a complete, runnable project for one framework and language, with
// a README that says how to run it and what still needs a person.
import { playwrightTypescript, playwrightPython } from './playwright.js';
import { seleniumJava, seleniumPython, seleniumTypescript } from './selenium.js';
import { appiumJava, appiumPython, appiumTypescript } from './appium.js';
import { apiTypescript, apiJava, apiPython } from './api.js';
import { counts, sourceLabel } from './common.js';
import { FRAMEWORKS, LANGUAGE_LABELS } from '../model.js';

const EMITTERS = {
  'playwright/typescript': playwrightTypescript,
  'playwright/python': playwrightPython,
  'selenium/java': seleniumJava,
  'selenium/python': seleniumPython,
  'selenium/typescript': seleniumTypescript,
  'appium/java': appiumJava,
  'appium/python': appiumPython,
  'appium/typescript': appiumTypescript,
  'api/typescript': apiTypescript,
  'api/java': apiJava,
  'api/python': apiPython,
};

export const TARGETS = Object.keys(EMITTERS);

const STATUS_TEXT = {
  verified: 'verified on the app',
  found: 'element found on the app',
  ok: 'converted',
  guessed: 'locator guessed: check it',
  failed: 'failed on the app',
  manual: 'manual: TODO',
};

/** Per test: what each manual step became. */
export function report(plans) {
  return plans.map((plan) => ({
    id: plan.test.id,
    title: plan.test.title,
    ...counts(plan),
    actions: plan.actions.map((a) => ({
      source: sourceLabel(a.source),
      sourceText: a.source?.text ?? '',
      type: a.type,
      target: a.target?.description ?? null,
      locator: a.target?.locator ?? null,
      status: a.status ?? (a.type === 'manual' ? 'manual' : a.target && !a.target.resolved ? 'guessed' : 'ok'),
      note: a.note ?? null,
    })),
  }));
}

function readme({ framework, language, plans, out, baseUrl, explored, rows }) {
  const fw = FRAMEWORKS[framework].label;
  const lang = LANGUAGE_LABELS[language];
  const totalTodo = rows.reduce((n, r) => n + r.todo, 0);
  return `# ${fw} tests (${lang})

Generated by **automation-script-agent** from ${plans.length} manual test case${plans.length === 1 ? '' : 's'}${explored ? ` and checked against ${baseUrl}` : ''}.

## Run

${out.run.map((r) => `- \`${r}\``).join('\n')}

## Settings

| Variable | What | Default |
| --- | --- | --- |
${out.env.map(([k, what, def]) => `| \`${k}\` | ${what} | \`${def}\` |`).join('\n')}

## What was converted

| Test | Actions | To review |
| --- | --- | --- |
${rows.map((r) => `| ${[r.id, r.title].filter(Boolean).join(' ')} | ${r.automated} of ${r.total} automated | ${r.todo || '—'} |`).join('\n')}

${totalTodo ? `Search the tests for \`TODO\` and \`NOTE\`:

- **TODO (manual)**: a step that could not be turned into code (a visual check, an email, a value the test didn't give).
- **TODO: locator guessed**: ${explored ? 'the element could not be found on the app' : 'no app was explored'}, so the locator comes from the step's words. Check it.
- **NOTE: did not hold on the live app**: the step ran, but the app did not behave as the manual test expects. Either the test or the app is wrong.` : 'Every step was converted.'}

Each line of code has a comment naming the manual step it came from. \`conversion-report.json\` lists every step, its locator and its status.
`;
}

/** { framework, language } -> { files: [{ path, content }], report, run } */
export function generateProject(plans, { framework, language, baseUrl = '', explored = false, projectName }) {
  const key = `${framework}/${language}`;
  const emit = EMITTERS[key];
  if (!emit) throw new Error(`Unsupported target ${key}. Choose one of: ${TARGETS.join(', ')}`);
  const name = projectName || `${framework}-${language}-tests`;
  const out = emit(plans, { baseUrl, projectName: name });
  const rows = report(plans);
  const files = [
    ...out.files,
    { path: 'README.md', content: readme({ framework, language, plans, out, baseUrl, explored, rows }) },
    { path: 'conversion-report.json', content: JSON.stringify({ framework, language, baseUrl: baseUrl || null, explored, tests: rows }, null, 2) + '\n' },
  ];
  return { files, report: rows, run: out.run, statusText: STATUS_TEXT };
}
